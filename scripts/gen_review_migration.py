def extract(name):
    """Latest definition of public.<name> across the original migrations."""
    found = None
    pattern = re.compile(r"create or replace function public\." + re.escape(name) + r"\(.*?\n\$\$;\n", re.S)
    for text in sources.values():
        for m in pattern.finditer(text):
            found = m.group(0)
    assert found, f"function {name} not found"
    return found


def edit(text, old, new, count=1):
    assert text.count(old) >= 1, f"anchor not found: {old[:80]!r}"
    return text.replace(old, new, count)


